"""Generate a 6x8 bitmap font header for the ST7735 status screen.

Rasterises ASCII 0x20..0x7E with a monospaced TrueType font (DejaVu Sans Mono
by default) into one byte per column, LSB = top row, and writes
firmware/src/font6x8.h. Run once; the header is committed.
"""

import argparse
import pathlib

from PIL import Image, ImageDraw, ImageFont

CANDIDATES = [
    r"C:\Windows\Fonts\DejaVuSansMono.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf",
    r"C:\Windows\Fonts\consola.ttf",
]


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--font", type=pathlib.Path)
    p.add_argument("--out", type=pathlib.Path,
                   default=pathlib.Path(__file__).resolve().parents[1] / "src" / "font6x8.h")
    a = p.parse_args()
    path = a.font or next((pathlib.Path(c) for c in CANDIDATES if pathlib.Path(c).exists()), None)
    if path is None:
        raise SystemExit("no monospaced TTF found; pass --font")
    font = ImageFont.truetype(str(path), 10)
    glyphs = []
    for code in range(0x20, 0x7F):
        im = Image.new("L", (6, 8), 0)
        ImageDraw.Draw(im).text((0, -2), chr(code), fill=255, font=font)
        cols = []
        for x in range(6):
            v = 0
            for y in range(8):
                if im.getpixel((x, y)) > 110:
                    v |= 1 << y
            cols.append(v)
        glyphs.append((code, cols))
    lines = ["/* Generated by firmware/scripts/gen_font.py from %s; do not edit. */" % path.name,
             "#pragma once", "#include <stdint.h>",
             "#define FONT_W 6", "#define FONT_H 8", "#define FONT_FIRST 0x20", "#define FONT_LAST 0x7E",
             "/* One byte per column, bit 0 = top row. */",
             "static const uint8_t kFont6x8[95][6] = {"]
    for code, cols in glyphs:
        lines.append("\t{" + ", ".join("0x%02x" % c for c in cols) + "}, /* '%s' */" % (chr(code) if code != 0x5C else "backslash"))
    lines.append("};")
    a.out.write_text("\n".join(lines) + "\n")
    print("wrote", a.out, "from", path)


if __name__ == "__main__":
    main()
